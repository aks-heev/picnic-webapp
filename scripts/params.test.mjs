import { readSearchParams as r, appendSearchParams, istToday, defaultTierForOccasion } from '../params.js'
const NOW = Date.parse('2026-10-29T18:00:00Z') // 23:30 IST Oct 29
let fail = 0
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? 'ok  ' : 'FAIL', name, ok ? '' : JSON.stringify(got) + ' != ' + JSON.stringify(want)) }
eq('ist today', istToday(NOW), '2026-10-29')
eq('ist rolls at 18:30Z', istToday(Date.parse('2026-10-29T18:31:00Z')), '2026-10-30')
eq('all valid', r('?occasion=Birthday&city=Gurugram&date=2026-11-14&guests=4', NOW), { occasion: 'Birthday', city: 'Gurugram', date: '2026-11-14', guests: 4 })
eq('empty', r('', NOW), { occasion: '', city: '', date: '', guests: null })
eq('occasion case-sensitive', r('?occasion=birthday', NOW).occasion, '')
eq('occasion with space', r('?occasion=Date%20Night', NOW).occasion, 'Date Night')
eq('occasion plus-encoded', r('?occasion=Date+Night', NOW).occasion, 'Date Night')
eq('unknown occasion', r('?occasion=Wedding', NOW).occasion, '')
eq('past date', r('?date=2026-10-28', NOW).date, '')
eq('today ok', r('?date=2026-10-29', NOW).date, '2026-10-29')
eq('impossible date', r('?date=2026-02-30', NOW).date, '')
eq('bad format', r('?date=14/11/2026', NOW).date, '')
eq('year 0026 typo', r('?date=0026-11-14', NOW).date, '')
eq('too far ahead', r('?date=2028-01-01', NOW).date, '')
eq('guests 0', r('?guests=0', NOW).guests, null)
eq('guests 31', r('?guests=31', NOW).guests, null)
eq('guests 30', r('?guests=30', NOW).guests, 30)
eq('guests text', r('?guests=4abc', NOW).guests, null)
eq('guests decimal', r('?guests=2.5', NOW).guests, null)
eq('city script', r('?city=%3Cscript%3E', NOW).city, '')
eq('city trimmed', r('?city=%20Jaipur%20', NOW).city, 'Jaipur')
eq('object input', r({ occasion: 'Proposal', guests: 2 }, NOW), { occasion: 'Proposal', city: '', date: '', guests: 2 })
eq('append skips empty', appendSearchParams(new URLSearchParams('tier=story'), r('?occasion=Proposal&guests=x', NOW)).toString(), 'tier=story&occasion=Proposal')
eq('default tier', [defaultTierForOccasion('Proposal'), defaultTierForOccasion('Birthday'), defaultTierForOccasion('nope')], ['story', 'moment', 'setting'])
console.log(fail ? `${fail} FAILED` : 'all passed'); process.exit(fail ? 1 : 0)
